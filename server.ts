// POST /api/predict - Real-time regression inference
app.post('/api/predict', (req, res) => {
  try {
    const { features, model } = req.body as {
      features: PropertyFeatures;
      model?: ModelAlgorithm;
    };

    if (!features || !features.location || !features.area_sqft) {
      return res.status(400).json({ error: 'Invalid property features submitted' });
    }

    const prediction = predictHousePrice(features, model || 'gradient_boosting');

    // Find 3 most comparable actual listings from dataset
    const comps = HOUSING_DATASET
      .filter((d) => d.location === features.location)
      .map((d) => ({
        ...d,
        areaDiff: Math.abs(d.area_sqft - features.area_sqft),
        bedDiff: Math.abs(d.bedrooms - features.bedrooms),
        bathDiff: Math.abs(d.bathrooms - features.bathrooms),
        similarityScore:
          100 -
          (Math.abs(d.area_sqft - features.area_sqft) / features.area_sqft) * 40 -
          Math.abs(d.bedrooms - features.bedrooms) * 15 -
          Math.abs(d.bathrooms - features.bathrooms) * 15,
      }))
      .sort((a, b) => b.similarityScore - a.similarityScore)
      .slice(0, 4);

    res.json({
      prediction,
      comparableProperties: comps,
      timestamp: new Date().toISOString(),
    });
  } catch (err: any) {
    res.status(500).json({ error: err.message || 'Prediction failed' });
  }
});

